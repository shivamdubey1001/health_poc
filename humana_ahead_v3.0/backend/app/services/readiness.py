SERVICE_MAP = {
    "Total knee replacement": ("KNEE_ARTHROPLASTY", "Orthopedic Surgery"),
    "Total hip replacement": ("HIP_ARTHROPLASTY", "Orthopedic Surgery"),
    "Cataract surgery": ("CATARACT_SURGERY", "Ophthalmology"),
}

# Documented weights, surfaced to the UI so an advocate can see what drives a
# score rather than being handed an unexplained number.
SCORE_WEIGHTS = {
    "coverage_not_covered": 25,
    "coverage_unknown": 10,
    "network_out_of_network": 30,
    "network_unknown": 8,
    "authorization_missing": 25,
    "authorization_in_progress": 10,
    "authorization_unknown": 8,
    "referral_conditional": 5,
    "cost_unknown": 10,
}

WEIGHT_RATIONALE = (
    "Deductions reflect member cost exposure and advocate effort to resolve. "
    "Out-of-network carries the largest weight because it has the greatest "
    "financial consequence for the member and the longest lead time to correct. "
    "These are a configurable v1 heuristic, not an empirically derived model."
)

READINESS_AGENT_PROMPT = """You are Agent 2, the Administrative Readiness Agent for a payer Member Advocate application.
The application has already performed deterministic lookups for plan coverage, provider/facility network, prior authorization, referral rules, member cost-share context, and relevant supplemental benefits.

You MUST NOT change, invent, or reinterpret the factual checklist statuses or readiness score. Your job is only to prioritize the unresolved administrative issue and propose a concise next administrative action for a Member Advocate.

Do not provide clinical advice, diagnosis, treatment recommendations, or guarantees of coverage. If every relevant item is READY or NOT_APPLICABLE, say that no major administrative action is identified and recommend monitoring/confirming final details.

Return exactly one JSON object:
{
  "top_issue_key": "one checklist key" or null,
  "recommended_next_action": "one concise, actionable administrative sentence"
}
Never reveal chain-of-thought."""


MIN_NAME_LENGTH = 5


def _mentions(name: str | None, text: str) -> bool:
    """Word-boundary match.

    A raw substring test matched a provider called Lee inside the word believe,
    and Park inside parking. Because this resolution drives network status, and
    network status carries the largest deduction in the scoring system, a false
    match could move a member from ninety-five per cent to forty. Word
    boundaries plus a length floor remove that class of error.
    """
    if not name or len(name.strip()) < MIN_NAME_LENGTH:
        return False
    return re.search(rf"\b{re.escape(name.strip().lower())}\b", text) is not None


def _find_likely_provider_ids(db: Session, member_id: str, specialty: str,
                              ) -> tuple[str | None, str | None, list[str]]:
    """Resolve the likely provider and facility from administrative records only.

    Structured sources are consulted FIRST - authorization records, then claims -
    because they are reliable. Free-text mention in a call summary is the last
    resort, and is word-boundary matched. No provider name is ever generated by
    the model. The third return value records which source won, so the UI can
    show how a provider was identified.
    """
    practitioner_id: str | None = None
    facility_id: str | None = None
    provenance: list[str] = []

    # 1. Prior authorizations - the most reliable administrative signal.
    pas = (db.query(models.PriorAuthorization)
           .filter(models.PriorAuthorization.member_id == member_id)
           .order_by(models.PriorAuthorization.request_date.desc()).all())
    for pa in pas:
        provider = db.get(models.ProviderDirectory, pa.requesting_provider_id) if pa.requesting_provider_id else None
        if not practitioner_id and provider and provider.specialty == specialty:
            practitioner_id = provider.provider_id
            provenance.append("surgeon resolved from authorization record")
        if not facility_id and pa.facility_id:
            facility_id = pa.facility_id
            provenance.append("facility resolved from authorization record")
        if practitioner_id and facility_id:
            return practitioner_id, facility_id, provenance

    # 2. Adjudicated claims.
    claims = (db.query(models.ClaimHistory)
              .filter(models.ClaimHistory.member_id == member_id)
              .order_by(models.ClaimHistory.service_from_date.desc()).all())
    for claim in claims:
        provider = db.get(models.ProviderDirectory, claim.provider_id) if claim.provider_id else None
        if not practitioner_id and provider and provider.specialty == specialty:
            practitioner_id = provider.provider_id
            provenance.append("surgeon resolved from recent claim")
        if not facility_id and claim.facility_id:
            claim_facility = db.get(models.ProviderDirectory, claim.facility_id)
            if claim_facility and claim_facility.provider_type == "FACILITY":
                facility_id = claim_facility.provider_id
                provenance.append("facility resolved from recent claim")
        if practitioner_id and facility_id:
            return practitioner_id, facility_id, provenance

    # 3. Free text, last resort, word-boundary matched.
    if not practitioner_id or not facility_id:
        summaries = (db.query(models.AgentAssistSummary)
                     .filter(models.AgentAssistSummary.member_id == member_id)
                     .order_by(models.AgentAssistSummary.call_start_timestamp.desc())
                     .limit(6).all())
        text = " ".join(((s.summary_text or "") + " " + (s.follow_up_note or ""))
                        for s in summaries).lower()
        if not practitioner_id:
            for provider in db.query(models.ProviderDirectory).filter(
                models.ProviderDirectory.provider_type == "PRACTITIONER",
                models.ProviderDirectory.specialty == specialty,
            ).all():
                if _mentions(provider.provider_name, text):
                    practitioner_id = provider.provider_id
                    provenance.append("surgeon named in a recent call summary")
                    break
        if not facility_id:
            for facility in db.query(models.ProviderDirectory).filter(
                models.ProviderDirectory.provider_type == "FACILITY"
            ).all():
                if _mentions(facility.provider_name, text) or _mentions(facility.organization_name, text):
                    facility_id = facility.provider_id
                    provenance.append("facility named in a recent call summary")
                    break

    return practitioner_id, facility_id, provenance


def _network_status(db: Session, plan_id: str, provider_id: str | None):
    if not provider_id:
        return None
    return db.query(models.ProviderNetwork).filter(
        models.ProviderNetwork.plan_id == plan_id,
        models.ProviderNetwork.provider_id == provider_id,
    ).first()


def get_alternatives(db: Session, member_id: str, specialty: str, provider_type: str | None = None, limit: int = 3) -> list[ProviderAlternative]:
    member = db.get(models.MemberEnrollment, member_id)
    if not member:
        return []
    q = db.query(models.ProviderDirectory).join(
        models.ProviderNetwork, models.ProviderNetwork.provider_id == models.ProviderDirectory.provider_id
    ).filter(
        models.ProviderNetwork.plan_id == member.plan_id,
        models.ProviderNetwork.network_status == "IN_NETWORK",
        models.ProviderDirectory.accepting_new_patients.is_(True),
    )
    if provider_type:
        q = q.filter(models.ProviderDirectory.provider_type == provider_type)
    if specialty:
        q = q.filter(models.ProviderDirectory.specialty == specialty)
    providers = q.all()
    providers.sort(key=lambda p: (0 if p.zip3 == member.zip3 else 1, p.city, p.provider_name))
    return [ProviderAlternative(
        provider_id=p.provider_id,
        provider_name=p.provider_name,
        organization_name=p.organization_name,
        specialty=p.specialty,
        city=p.city,
        state=p.state,
        zip3=p.zip3,
        network_status="IN_NETWORK",
        accepting_new_patients=p.accepting_new_patients,
    ) for p in providers[:limit]]


