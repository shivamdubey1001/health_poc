"""Agent 2 - Administrative Readiness.

Every factual status and the score itself are computed deterministically in
Python. The model receives the finished checklist and does exactly two things:
choose which unresolved item to surface first, and write one advocate-facing
sentence. Its choice is validated against the real checklist and discarded if it
names an invalid or already-resolved key.

Score weights encode two things: the member cost exposure an unresolved item
creates, and the effort required to resolve it. Out-of-network carries the
largest deduction because it has the largest financial consequence for the
member and the longest lead time to fix. They are a v1 heuristic, configurable,
and would be re-derived from actual advocate resolution times in a pilot.
"""

